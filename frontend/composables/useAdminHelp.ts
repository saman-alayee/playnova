export function getAdminHelp(path: string): AdminHelpContent | null {
  const normalized = path.replace(/\/$/, '') || '/admin'
  const rule = RULES.find((r) => r.match(normalized))
  return rule?.content ?? null
}

export function useAdminHelp() {
  const route = useRoute()
  const help = computed(() => getAdminHelp(route.path))
  return { help }
}
